// Builds src/environments/globe/landMaskData.ts: a one-bit land/sea map of the Earth, one cell per
// degree, from Natural Earth's 110m land polygons (public domain, naturalearthdata.com).
//
//   node scripts/build-land-mask.mjs [path-or-url-to-ne_110m_land.geojson]
//
// The output is committed, so this only needs running to regenerate the map.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT_SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const WIDTH = 360;
const HEIGHT = 180;

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'src/environments/globe/landMaskData.ts');
const source = process.argv[2] ?? DEFAULT_SOURCE;

async function load(from) {
  if (/^https?:/.test(from)) {
    const response = await fetch(from);
    if (!response.ok) throw new Error(`Could not download ${from}: ${response.status}`);
    return response.json();
  }
  return JSON.parse(await readFile(from, 'utf8'));
}

/** Every polygon as a list of rings, each ring a flat [lon, lat, lon, lat, …] array with its bounds. */
function collectPolygons(geojson) {
  const polygons = [];
  for (const feature of geojson.features) {
    const { type, coordinates } = feature.geometry;
    const parts = type === 'Polygon' ? [coordinates] : type === 'MultiPolygon' ? coordinates : [];
    for (const part of parts) {
      let minLon = Infinity;
      let maxLon = -Infinity;
      let minLat = Infinity;
      let maxLat = -Infinity;
      const rings = part.map((ring) => {
        const flat = new Float64Array(ring.length * 2);
        ring.forEach(([lon, lat], i) => {
          flat[i * 2] = lon;
          flat[i * 2 + 1] = lat;
          minLon = Math.min(minLon, lon);
          maxLon = Math.max(maxLon, lon);
          minLat = Math.min(minLat, lat);
          maxLat = Math.max(maxLat, lat);
        });
        return flat;
      });
      polygons.push({ rings, minLon, maxLon, minLat, maxLat });
    }
  }
  return polygons;
}

/** Even-odd rule across all rings, so holes (lakes cut out of land) count as water. */
function inside(polygon, lon, lat) {
  if (lon < polygon.minLon || lon > polygon.maxLon) return false;
  if (lat < polygon.minLat || lat > polygon.maxLat) return false;
  let hit = false;
  for (const ring of polygon.rings) {
    for (let i = 0, j = ring.length - 2; i < ring.length; j = i, i += 2) {
      const xi = ring[i];
      const yi = ring[i + 1];
      const xj = ring[j];
      const yj = ring[j + 1];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
}

const polygons = collectPolygons(await load(source));
const bits = new Uint8Array((WIDTH * HEIGHT) / 8);
let land = 0;
for (let row = 0; row < HEIGHT; row++) {
  const lat = 90 - (row + 0.5) * (180 / HEIGHT);
  for (let col = 0; col < WIDTH; col++) {
    const lon = -180 + (col + 0.5) * (360 / WIDTH);
    if (!polygons.some((polygon) => inside(polygon, lon, lat))) continue;
    const index = row * WIDTH + col;
    bits[index >> 3] |= 1 << (index & 7);
    land++;
  }
}

const base64 = Buffer.from(bits).toString('base64');
const lines = base64.match(/.{1,96}/g).map((line) => `  '${line}',`);
await writeFile(
  output,
  `// Generated by scripts/build-land-mask.mjs from Natural Earth 110m land (public domain).
// Do not edit by hand.

export const LAND_MASK_WIDTH = ${WIDTH};
export const LAND_MASK_HEIGHT = ${HEIGHT};

/** One bit per cell, row by row from the north pole, starting at 180° west; set means land. */
// prettier-ignore
export const LAND_MASK_BASE64 = [
${lines.join('\n')}
].join('');
`,
);
console.log(
  `[land-mask] ${WIDTH}x${HEIGHT}, ${((land / (WIDTH * HEIGHT)) * 100).toFixed(1)}% of cells are land, ${base64.length} characters -> ${output}`,
);
